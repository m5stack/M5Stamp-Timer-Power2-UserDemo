#!/usr/bin/env python3
"""Embed the offline setup/control Web UI into the firmware as gzip assets."""
from __future__ import annotations

import argparse
import gzip
import pathlib
import re
import sys

MIME = {
    ".html": "text/html; charset=utf-8",
    ".js": "application/javascript; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".json": "application/json; charset=utf-8",
    ".svg": "image/svg+xml",
    ".jpg": "image/jpeg",
    ".jpeg": "image/jpeg",
    ".png": "image/png",
    ".ico": "image/x-icon",
}


def route_for(rel: str) -> str:
    return "/" if rel == "index.html" else "/" + rel


def symbol_for(rel: str) -> str:
    return "asset_" + re.sub(r"[^a-zA-Z0-9_]", "_", rel)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--src", required=True)
    parser.add_argument("--out", required=True)
    args = parser.parse_args()

    src = pathlib.Path(args.src).resolve()
    out = pathlib.Path(args.out).resolve()
    web_suffixes = {".html", ".js", ".css", ".json", ".svg", ".jpg", ".jpeg", ".png", ".ico"}
    files = sorted(p for p in src.rglob("*") if p.is_file() and p.suffix.lower() in web_suffixes)
    if not files:
        raise SystemExit(f"no web assets found in {src}")

    entries = []
    lines = [
        "// Generated by scripts/embed_web.py. Do not edit.",
        "#pragma once",
        "#include <Arduino.h>",
        "#include <stddef.h>",
        "",
        "struct WebAsset {",
        "  const char* path;",
        "  const char* content_type;",
        "  const uint8_t* data;",
        "  size_t size;",
        "};",
        "",
    ]
    for idx, file in enumerate(files):
        rel = file.relative_to(src).as_posix()
        raw = file.read_bytes()
        data = gzip.compress(raw, compresslevel=9, mtime=0)
        sym = symbol_for(rel)
        lines.append(f"static const uint8_t {sym}[] PROGMEM = {{")
        for pos in range(0, len(data), 16):
            chunk = ", ".join(f"0x{b:02X}" for b in data[pos : pos + 16])
            lines.append("  " + chunk + ",")
        lines.append("};")
        entries.append((route_for(rel), MIME.get(file.suffix.lower(), "application/octet-stream"), sym, len(data)))
        print(f"embedded {rel:<24} {len(raw):>7} -> {len(data):>6} bytes")

    lines.append("static const WebAsset WEB_ASSETS[] = {")
    for route, mime, sym, size in entries:
        lines.append(f'  {{"{route}", "{mime}", {sym}, {size}}},')
    lines.append("};")
    lines.append(f"static constexpr size_t WEB_ASSET_COUNT = {len(entries)};")
    lines.append("")

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out} ({out.stat().st_size} bytes source)")
    return 0


# PlatformIO executes extra scripts inside SCons. Regenerate before every build.
try:
    Import("env")  # type: ignore[name-defined]
    import os
    import subprocess

    _project = pathlib.Path(env.subst("$PROJECT_DIR"))  # type: ignore[name-defined]
    _cmd = [
        sys.executable,
        str(_project / "scripts" / "embed_web.py"),
        "--src",
        str(_project / "esp_web"),
        "--out",
        str(_project / "include" / "web_assets.h"),
    ]

    def _generate_web_assets(*_args, **_kwargs):
        subprocess.check_call(_cmd, cwd=_project, env=os.environ.copy())

    _generate_web_assets()
    env.AddPreAction("buildprog", _generate_web_assets)  # type: ignore[name-defined]
except NameError:
    # Normal CLI invocation outside PlatformIO.
    pass


if __name__ == "__main__":
    sys.exit(main())
